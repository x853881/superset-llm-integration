"""A JSONL on-disk cache of (text, model) -> embedding vector, so repeated
requests against the same text don't re-pay for (or re-wait on) an embedding
call. One JSON object per line: ``{"text": ..., "model": ..., "embedding": [...]}``.

``EmbeddingCache``: ``load`` reads
whatever's cached so far from this extension's own bundled resource
(``resources/embeddings_cache.jsonl``, embedded as a Python literal in
``resources/embeddings_cache_data.py`` - see that file for why - generated by
that a schema-description pipeline for the same Postgres
database). Entries ``put`` afterwards are appended back to the *source*
``.jsonl`` file on disk if it can be found there - true when this extension
is loaded via ``LOCAL_EXTENSIONS`` from a real dev checkout, never true when
loaded from a packaged ``.supx`` (see the module docstring in
``resources/embeddings_cache_data.py``: there's no real file to find at all
in that case), in which case writes are silently skipped. The point is to
grow the checked-in cache during development, not to persist anything for an
end user.
"""

from __future__ import annotations

import json
import logging
import threading
from pathlib import Path
from typing import Optional

from .resources.embeddings_cache_data import EMBEDDINGS_CACHE_JSONL

logger = logging.getLogger(__name__)

CacheKey = tuple[str, str]


class EmbeddingCache:
    def __init__(self, entries: dict[CacheKey, list[float]], source_file: Optional[Path]):
        self._entries = dict(entries)
        self._source_file = source_file
        self._lock = threading.Lock()

    @classmethod
    def load(cls) -> "EmbeddingCache":
        entries: dict[CacheKey, list[float]] = {}
        for line in EMBEDDINGS_CACHE_JSONL.splitlines():
            line = line.strip()
            if not line:
                continue
            entry = json.loads(line)
            entries[(entry["text"], entry["model"])] = entry["embedding"]

        source_file = _find_writable_source_file()
        logger.info(
            "embedding_cache_loaded entries=%d source_file=%s writable=%s",
            len(entries), source_file, source_file is not None,
        )
        return cls(entries, source_file)

    def get(self, text: str, model: str) -> Optional[list[float]]:
        return self._entries.get((text, model))

    def put(self, text: str, model: str, vector: list[float]) -> None:
        key = (text, model)
        with self._lock:
            # Already cached - either a previous call, or we lost a race with a concurrent one;
            # either way there's nothing new to append.
            if key in self._entries:
                return
            self._entries[key] = vector

        if self._source_file is None:
            return
        try:
            line = json.dumps({"text": text, "model": model, "embedding": vector})
            with self._source_file.open("a") as f:
                f.write(line + "\n")
        except OSError as ex:
            logger.warning("embedding_cache_write_failed path=%s error=%s", self._source_file, ex)


def _find_writable_source_file() -> Optional[Path]:
    """``__file__`` points at a real file on disk when this extension is loaded via
    ``LOCAL_EXTENSIONS`` (a dev checkout's ``dist/`` directory), but at a virtual ``supx://`` URI
    when loaded from a packaged ``.supx`` - `Path(...).is_file()` safely returns False rather than
    raising for the latter, so this degrades to "not writable" there without any special-casing."""
    candidate = Path(__file__).resolve().parent / "resources" / "embeddings_cache.jsonl"
    return candidate if candidate.is_file() else None
